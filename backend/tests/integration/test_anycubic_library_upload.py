"""Library storage preserves raw files for the selected provider's inspection."""

import hashlib

import pytest

from backend.app.models.printer import Printer
from plugins.anycubic.payload.plugin import AnycubicPrinterPlugin

pytestmark = [pytest.mark.asyncio, pytest.mark.integration]

GCODE = b"""; generated by AnycubicSlicerNext 2.0.0.3
; printer_model = Anycubic Kobra S1
; filament_type = PLA
; filament_colour = #112233
; filament used [mm] = 100
; filament used [g] = 3.5
T0
G1 X1 Y1
M400
"""


@pytest.fixture
async def anycubic_printer(db_session, tmp_path, monkeypatch):
    from backend.app.core.config import settings
    from backend.app.printers import api, registry as registry_module
    from backend.app.services.printer_manager import printer_manager

    monkeypatch.setattr(settings, "base_dir", tmp_path)
    monkeypatch.setattr(settings, "archive_dir", tmp_path / "archive")
    monkeypatch.setattr(registry_module, "entry_points", lambda **kwargs: [])
    registry = registry_module.PrinterPluginRegistry()
    monkeypatch.setattr(registry_module, "registry", registry)
    registry.load()
    plugin = AnycubicPrinterPlugin()
    registry.register(plugin)
    monkeypatch.setattr(api, "_bindings", {})
    for name in ("_clients", "_configs", "_models", "_printer_info", "_last_trays"):
        monkeypatch.setattr(printer_manager, name, {})

    printer = Printer(
        name="Offline upload fixture",
        ip_address="192.168.50.50",
        serial_number="RAW-UPLOAD-ONLY",
        access_code="",
        model="Kobra S1",
        plugin_id=plugin.id,
        plugin_options={"tls_fingerprint": "a" * 64},
    )
    db_session.add(printer)
    await db_session.commit()
    await db_session.refresh(printer)
    yield printer
    # Inspection must not create a connection or start printer network I/O.
    assert plugin.connections == {}
    assert printer_manager._clients == {}


async def upload_raw_gcode(async_client, content):
    response = await async_client.post(
        "/api/v1/library/files",
        files={"file": ("S1_ForeArm_PLA.gcode", content, "application/octet-stream")},
    )
    assert response.status_code == 200, response.text
    uploaded = response.json()
    assert uploaded["filename"] == "S1_ForeArm_PLA.gcode"
    assert uploaded["file_type"] == "gcode"
    assert uploaded["file_size"] == len(content)
    return uploaded


async def test_uploaded_raw_gcode_supplies_anycubic_materials_and_print_options(async_client, anycubic_printer):
    uploaded = await upload_raw_gcode(async_client, GCODE)
    response = await async_client.post(
        f"/api/v1/printers/{anycubic_printer.id}/job-description",
        json={"library_file_id": uploaded["id"]},
    )
    assert response.status_code == 200, response.text
    description = response.json()
    artifact = description["artifact"]
    assert artifact["uri"] == f"library:{uploaded['id']}"
    assert artifact["filename"] == uploaded["filename"]
    assert artifact["format"] == "gcode"
    assert artifact["sha256"] == hashlib.sha256(GCODE).hexdigest()
    assert len(description["inputs"]) == 1
    sliced_input = description["inputs"][0]
    assert sliced_input["id"] == "T0"
    assert sliced_input["material_type"] == "PLA"
    assert sliced_input["color"] == "#112233FF"
    assert sliced_input["required_mass_grams"] == 3.5
    assert sliced_input["compatible_tool_ids"] == ["tool:primary"]
    assert "material:external" in sliced_input["compatible_source_ids"]
    assert "material:ace:0:0" in sliced_input["compatible_source_ids"]
    options = description["options_schema"]["properties"]
    assert options["use_ace"]["title"] == "Use ACE"
    assert options["auto_leveling"]["title"] == "Bed leveling"
    assert description["default_options"]["use_ace"] is True
    assert description["extensions"]["bambuddy:ui"]["material_mode"]["source_placeholder"] == "Select ACE slot"

    downloaded = await async_client.get(f"/api/v1/library/files/{uploaded['id']}/download")
    assert downloaded.status_code == 200, downloaded.text
    assert downloaded.content == GCODE


@pytest.mark.parametrize(
    "content",
    [
        GCODE.replace(b"Kobra S1", b"Kobra 3"),
        GCODE + b"\x00",
        GCODE.replace(b"; filament_type = PLA\n", b""),
    ],
    ids=["different-model", "invalid-text", "missing-material"],
)
async def test_stored_gcode_still_requires_provider_compatibility(async_client, anycubic_printer, content):
    uploaded = await upload_raw_gcode(async_client, content)
    response = await async_client.post(
        f"/api/v1/printers/{anycubic_printer.id}/job-description",
        json={"library_file_id": uploaded["id"]},
    )
    assert response.status_code == 422, response.text
    assert response.json()["detail"]
