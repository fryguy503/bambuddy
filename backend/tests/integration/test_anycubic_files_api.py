import time
from types import SimpleNamespace
from unittest.mock import MagicMock, patch

import pytest

from backend.app.api.routes import anycubic_files as routes
from backend.app.models.printer import Printer
from backend.app.services.anycubic import AnycubicMQTTClient


@pytest.fixture
async def target(db_session):
    printer = Printer(
        name="Fixture S1",
        serial_number="fixture-id",
        ip_address="192.168.1.50",
        access_code="",
        model="Kobra S1",
        printer_type="anycubic",
        tls_fingerprint="a" * 64,
    )
    db_session.add(printer)
    await db_session.commit()
    await db_session.refresh(printer)
    client = AnycubicMQTTClient(
        printer.ip_address, printer.serial_number, model=printer.model, tls_fingerprint=printer.tls_fingerprint
    )
    client.state.connected = True
    client._last_message_monotonic = time.monotonic()
    client._publish = MagicMock()
    with patch.object(routes.printer_manager, "get_client", return_value=client):
        yield printer, client


async def test_catalog_uses_native_list_and_never_bambu_ftps(async_client, target):
    printer, client = target
    client.list_files = MagicMock(return_value={"path": "/", "files": [], "total": 0, "page": 1, "pages": 0})
    response = await async_client.get(f"/api/v1/printers/{printer.id}/anycubic/files")
    assert response.status_code == 200 and response.json()["files"] == []
    client.list_files.assert_called_once_with(path="/", page=1)
    client._publish.assert_not_called()


async def test_upload_validates_model_then_hands_off_only_a_private_staged_export(async_client, target):
    printer, client = target
    captured = []

    def start(printer_id, connection, artifact, staging):
        assert printer_id == printer.id and connection is client
        assert artifact.path.is_file() and artifact.model == "Kobra S1"
        captured.append((artifact.path, staging))
        return SimpleNamespace(
            public=lambda: {"id": "fixture-job", "filename": artifact.filename, "phase": "uploading"}
        )

    try:
        with (
            patch.object(routes.transfers, "active", return_value=False),
            patch.object(routes.transfers, "start", side_effect=start),
        ):
            response = await async_client.post(
                f"/api/v1/printers/{printer.id}/anycubic/files/upload",
                files={
                    "file": (
                        "example.gcode",
                        b"; generated by AnycubicSlicerNext\n; printer_model = Kobra S1\nG1 X1\n",
                        "text/plain",
                    )
                },
            )
        assert response.status_code == 202 and response.json()["id"] == "fixture-job"
        assert str(captured[0][0]) not in response.text
        client._publish.assert_not_called()
    finally:
        for path, directory in captured:
            path.unlink(missing_ok=True)
            directory.rmdir()


async def test_invalid_export_is_cleaned_up_and_never_started(async_client, target, tmp_path):
    printer, client = target
    staging = tmp_path / "owned-stage"
    staging.mkdir()
    with (
        patch.object(routes.tempfile, "mkdtemp", return_value=str(staging)),
        patch.object(routes.transfers, "start") as start,
    ):
        response = await async_client.post(
            f"/api/v1/printers/{printer.id}/anycubic/files/upload",
            files={"file": ("wrong.gcode", b"; generated by OrcaSlicer\n; printer_model = Kobra 3\nG1 X1\n")},
        )
    assert response.status_code == 400
    assert not staging.exists() and printer.id not in routes._receiving
    start.assert_not_called()
    client._publish.assert_not_called()


async def test_replaced_connection_and_cross_printer_job_are_rejected(async_client, target):
    printer, client = target
    client._fingerprint = "b" * 64
    assert (await async_client.get(f"/api/v1/printers/{printer.id}/anycubic/files")).status_code == 503
    with patch.object(routes.transfers, "get", return_value=None):
        response = await async_client.get(f"/api/v1/printers/{printer.id}/anycubic/files/uploads/other-printer-job")
    assert response.status_code == 404
    client._publish.assert_not_called()


@pytest.mark.parametrize("control,scope", [(False, None), (True, [])])
async def test_upload_permissions_and_printer_scope_precede_staging(async_client, db_session, target, control, scope):
    from backend.app.core.auth import generate_api_key
    from backend.app.models.api_key import APIKey
    from backend.app.models.settings import Settings

    full, hashed, prefix = generate_api_key()
    db_session.add(
        APIKey(
            name="files-fixture",
            key_hash=hashed,
            key_prefix=prefix,
            can_control_printer=control,
            printer_ids=scope,
            enabled=True,
        )
    )
    db_session.add(Settings(key="auth_enabled", value="true"))
    await db_session.commit()
    printer, client = target
    with patch.object(routes.tempfile, "mkdtemp") as stage, patch.object(routes.transfers, "start") as start:
        response = await async_client.post(
            f"/api/v1/printers/{printer.id}/anycubic/files/upload",
            headers={"X-API-Key": full},
            files={"file": ("fixture.gcode", b"G1 X1")},
        )
    assert response.status_code in (403, 404), response.text
    stage.assert_not_called()
    start.assert_not_called()
    client._publish.assert_not_called()
