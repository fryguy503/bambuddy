async def test_unknown_dispatch_requires_idle_confirmation_and_survives_delete(
    async_client, native_source, db_session, monkeypatch
):
    from backend.app.services.printer_manager import printer_manager

    printer, source, _ = native_source
    row = PrintQueueItem(
        printer_id=printer.id,
        library_file_id=source.id,
        status="printing",
        anycubic_options=json.dumps(OPTIONS),
        anycubic_dispatch=json.dumps({"state": "unknown", "filename": "unique.gcode"}),
    )
    db_session.add(row)
    await db_session.commit()
    client = AnycubicMQTTClient(
        printer.ip_address, printer.serial_number, model=printer.model, tls_fingerprint=printer.tls_fingerprint
    )
    client.state.connected = True
    client.state.state = "RUNNING"
    client._last_state_time = time.monotonic()
    publish = MagicMock()
    monkeypatch.setattr(client, "_publish", publish)
    monkeypatch.setattr(printer_manager, "get_client", lambda _id: client)
    delete = await async_client.delete(f"/api/v1/queue/{row.id}")
    assert delete.status_code in (400, 409)
    assert await db_session.get(PrintQueueItem, row.id) is not None
    url = f"/api/v1/queue/{row.id}/resolve-anycubic"
    blocked = await async_client.post(url, json={"acknowledge_not_printing": True})
    assert blocked.status_code == 409
    client.state.state = "IDLE"
    result = await async_client.post(url, json={"acknowledge_not_printing": True})
    assert result.status_code == 200, result.text
    await db_session.refresh(row)
    assert row.status == "failed" and json.loads(row.anycubic_dispatch)["state"] == "resolved"
    publish.assert_not_called()


async def test_corrupt_dispatch_cannot_silently_release_its_printer_hold(async_client, native_source, db_session):
    printer, _, _ = native_source
    row = PrintQueueItem(
        printer_id=printer.id,
        status="cancelled",
        anycubic_options=json.dumps(OPTIONS),
        anycubic_dispatch="corrupt-internal-intent",
    )
    db_session.add(row)
    await db_session.commit()
    result = await async_client.delete(f"/api/v1/queue/{row.id}")
    assert result.status_code == 409
    assert await db_session.get(PrintQueueItem, row.id) is not None
