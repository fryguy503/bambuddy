async def test_stale_observer_cannot_overwrite_operator_resolution(case, monkeypatch):
    await dispatch(case)
    monkeypatch.setattr(native, "CONFIRM_SECONDS", 0)
    async with case.factory() as db:
        item = await db.get(PrintQueueItem, case.ids.item)
        original = native.journal(item.anycubic_dispatch)
        resolved = {**original, "state": "resolved"}
        await db.execute(
            update(PrintQueueItem)
            .where(PrintQueueItem.id == item.id)
            .values(anycubic_dispatch=json.dumps(resolved))
            .execution_options(synchronize_session=False)
        )
        await db.commit()
        assert not await native._observe(db, item, state(case, original, "IDLE"))
        await db.commit()
    assert native.journal((await row(case)).anycubic_dispatch)["state"] == "resolved"


