async def test_observed_running_job_wins_over_a_contradictory_rejected_receipt(case):
    loop = asyncio.get_running_loop()

    def submit(*_args, **_kwargs):
        with sqlite3.connect(case.db_path) as conn:
            raw = conn.execute("select anycubic_dispatch from print_queue where id = ?", (case.ids.item,)).fetchone()[0]
        observed = state(case, native.journal(raw), "RUNNING")
        asyncio.run_coroutine_threadsafe(
            native.observe_status(case.ids.printer, observed, session_factory=case.factory), loop
        ).result(timeout=5)
        return {"status": "rejected", "error": "Contradictory receipt"}

    case.client.submit_print.side_effect = submit
    await dispatch(case)
    item = await row(case)
    assert item.status == "printing"
    assert native.journal(item.anycubic_dispatch)["state"] == "running"
    async with case.factory() as db:
        assert await native.held_printer_ids(db) == {case.ids.printer}


