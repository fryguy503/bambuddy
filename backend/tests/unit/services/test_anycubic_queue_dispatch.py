async def dispatch(case):
    async with case.factory() as db:
        item = await db.get(PrintQueueItem, case.ids.item)
        printer = await db.get(Printer, case.ids.printer)
        await native.dispatch(case.scheduler, db, item, printer)


async def row(case):
    async with case.factory() as db:
        return await db.get(PrintQueueItem, case.ids.item)


def state(case, record, phase, task_id="native-task-7", filename=None):
    case.client.state.state = phase
    case.client.state.subtask_id = task_id
    case.client.state.gcode_file = filename if filename is not None else record["filename"]
    return case.client.state


async def test_intent_commits_before_publish_and_detaches_cascading_sources(case):
    def submit(*_args, **_kwargs):
        with sqlite3.connect(case.db_path) as conn:
            status, raw, library_id, archive_id = conn.execute(
                "select status, anycubic_dispatch, library_file_id, archive_id from print_queue where id = ?",
                (case.ids.item,),
            ).fetchone()
        assert status == "printing"
        assert json.loads(raw)["state"] == "submitting"
        assert (library_id, archive_id) == (None, None)
        return {"status": "accepted", "task_id": "native-task-7"}

    case.client.submit_print.side_effect = submit
    await dispatch(case)
    item = await row(case)
    record = native.journal(item.anycubic_dispatch)
    assert record["state"] == "accepted"
    assert record["source_library_file_id"] == case.ids.library
    assert case.client.submit_print.call_count == 1
    assert case.manager.start.call_count == 1
    async with case.factory() as db:
        archive = await db.get(PrintArchive, record["native_archive_id"])
        assert archive.sliced_for_model == "Kobra S1"
        assert (native.settings.base_dir / archive.file_path).read_bytes() == GCODE
        assert await native.held_printer_ids(db) == {case.ids.printer}


