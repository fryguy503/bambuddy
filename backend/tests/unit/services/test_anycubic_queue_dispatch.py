async def test_unverified_upload_does_not_submit_print(case):
    original = case.manager.start.side_effect

    def unverified(*args):
        job = original(*args)
        job.task.cancel()

        async def finish():
            job.phase = "uploaded_unverified"

        job.task = asyncio.create_task(finish())
        return job

    case.manager.start.side_effect = unverified
    await dispatch(case)
    assert (await row(case)).status == "failed"
    case.client.submit_print.assert_not_called()


