@pytest.mark.parametrize("phase", ["FINISH", "FAILED", "IDLE"])
async def test_manual_print_leaves_a_durable_plate_gate_once(case, phase):
    record = {"filename": "manual.gcode"}
    await native.observe_status(
        case.ids.printer, state(case, record, "RUNNING", task_id="manual"), session_factory=case.factory
    )
    await native.observe_status(
        case.ids.printer, state(case, record, phase, task_id="manual"), session_factory=case.factory
    )
    async with case.factory() as db:
        printer = await db.get(Printer, case.ids.printer)
        assert printer.awaiting_plate_clear is True
        printer.awaiting_plate_clear = False  # Operator acknowledged the empty plate.
        await db.commit()
    await native.observe_status(
        case.ids.printer, state(case, record, phase, task_id="manual"), session_factory=case.factory
    )
    async with case.factory() as db:
        assert (await db.get(Printer, case.ids.printer)).awaiting_plate_clear is False


