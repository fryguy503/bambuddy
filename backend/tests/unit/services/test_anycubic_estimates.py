"""Slicer-owned raw G-code estimates retain physical tool identity."""

import pytest

from backend.app.services.anycubic.printing import ESTIMATES_VERSION, inspect_print_file, merge_estimates
from backend.app.services.anycubic.protocol import AnycubicError

GCODE = b"""; generated by AnycubicSlicerNext 2.0.0.3
; printer_model = Anycubic Kobra S1
; filament_type = PLA;PLA Matte;PETG
; filament_colour = #FFC196;#112233;#445566
; filament used [mm] = 3309.77,0,0
T0
G1 X1 E1
"""
FOOTER = b"""; filament used [g] = 9.87,0,0
; total filament used [g] = 9.87
; estimated printing time (normal mode) = 26m 27s
; estimated printing time (silent mode) = 37m 47s
; estimated printing time (sport mode) = 24m 35s
"""


def inspect(tmp_path, footer=FOOTER, base=GCODE):
    path = tmp_path / "print.gcode"
    path.write_bytes(base + footer)
    return inspect_print_file(path, path.name, "Kobra S1")


def test_native_footer_estimates_use_normal_mode_and_existing_metadata_shape(tmp_path):
    artifact = inspect(tmp_path, base=GCODE + b"G1 X1\n" * 20000)
    assert artifact.estimates == {
        "anycubic_estimates_version": ESTIMATES_VERSION,
        "anycubic_estimates_sha256": artifact.file.sha256,
        "print_time_seconds": 1587,
        "filament_used_mm": 3309.77,
        "filament_used_grams": 9.87,
        "anycubic_tool_usage": [{"tool": 0, "grams": 9.87}],
        "filament_slots": [{"slot_id": 1, "used_g": 9.87, "type": "PLA", "color": "#FFC196FF"}],
    }
    assert artifact.public() == {"model": "Kobra S1", "tools": [{"tool": 0, "type": "PLA", "color": "FFC196FF"}]}


def test_sparse_tool_usage_does_not_compact_zero_entries(tmp_path):
    base = GCODE.replace(b"3309.77,0,0", b"100,0,200") + b"T2\nG1 X2 E2\n"
    estimates = inspect(tmp_path, b"; filament used [g] = 1.2,0,2.4\n; total filament used [g] = 3.6\n", base).estimates
    assert estimates["anycubic_tool_usage"] == [{"tool": 0, "grams": 1.2}, {"tool": 2, "grams": 2.4}]
    assert [entry["slot_id"] for entry in estimates["filament_slots"]] == [1, 3]
    assert estimates["filament_used_mm"] == 300
    assert estimates["filament_used_grams"] == 3.6


def test_aggregate_weight_is_displayable_without_inventing_tool_allocation(tmp_path):
    base = GCODE.replace(b"3309.77,0,0", b"100,0,200") + b"T2\nG1 X2 E2\n"
    estimates = inspect(tmp_path, b"; total filament used [g] = 3.6\n", base).estimates
    assert estimates["filament_used_grams"] == 3.6
    assert "anycubic_tool_usage" not in estimates
    assert "filament_slots" not in estimates


@pytest.mark.parametrize("vector", [b"9.87", b"9.87,0,2"])
def test_incomplete_or_unmapped_vectors_do_not_authorize_tool_usage(tmp_path, vector):
    base = GCODE + b"T2\nG1 X2 E2\n" if vector == b"9.87" else GCODE
    estimates = inspect(tmp_path, b"; filament used [g] = " + vector + b"\n", base).estimates
    assert "filament_used_grams" in estimates
    assert "anycubic_tool_usage" not in estimates


@pytest.mark.parametrize("value", [b"nan", b"inf", b"-1", b"1,bad", b"1,", b"1e308,1e308", b"1" * 17000])
def test_invalid_optional_weight_stays_unknown_without_weakening_print_validation(tmp_path, value):
    artifact = inspect(tmp_path, b"; filament used [g] = " + value + b"\n; total filament used [g] = 9.87\n")
    assert [entry.tool for entry in artifact.filaments] == [0]
    assert "filament_used_grams" not in artifact.estimates
    assert "anycubic_tool_usage" not in artifact.estimates


@pytest.mark.parametrize(
    "footer",
    [
        b"; filament used [g] = 1,0,0\n; total filament used [g] = 99\n",
        b"; filament used [g] = 1,0,0\n; filament used [g] = 2,0,0\n",
        b"; total filament used [g] = nan\n",
        b"; total filament used [g] = 1,2\n",
    ],
)
def test_contradictory_or_invalid_gram_estimates_are_not_chosen_silently(tmp_path, footer):
    estimates = inspect(tmp_path, footer).estimates
    assert "filament_used_grams" not in estimates
    assert "anycubic_tool_usage" not in estimates


@pytest.mark.parametrize("duration, expected", [(b"1d 2h 3m 4s", 93784), (b"0s", 0), (b"60m", 3600)])
def test_explicit_durations_are_converted_to_seconds(tmp_path, duration, expected):
    assert (
        inspect(tmp_path, b"; estimated printing time (normal mode) = " + duration + b"\n").estimates[
            "print_time_seconds"
        ]
        == expected
    )


@pytest.mark.parametrize("duration", [b"", b"nan", b"12", b"2m 1h", b"1h nonsense", b"999999999999d"])
def test_invalid_duration_does_not_become_a_zero_or_filename_guess(tmp_path, duration):
    assert (
        "print_time_seconds"
        not in inspect(tmp_path, b"; estimated printing time (normal mode) = " + duration + b"\n").estimates
    )


def test_missing_estimates_keep_unknown_values_and_a_bounded_backfill_marker(tmp_path):
    artifact = inspect(tmp_path, b"; estimated printing time (sport mode) = 1m\n")
    assert artifact.estimates == {
        "anycubic_estimates_version": ESTIMATES_VERSION,
        "anycubic_estimates_sha256": artifact.file.sha256,
        "filament_used_mm": 3309.77,
    }


def test_exact_duplicate_estimates_and_rounding_totals_are_usable(tmp_path):
    estimates = inspect(tmp_path, FOOTER + FOOTER).estimates
    assert estimates["filament_used_grams"] == 9.87
    rounded = inspect(tmp_path, b"; filament used [g] = 1.234\n; total filament used [g] = 1.23\n").estimates
    assert rounded["anycubic_tool_usage"] == [{"tool": 0, "grams": 1.234}]


def test_explicit_zero_grams_are_distinct_from_unknown(tmp_path):
    estimates = inspect(tmp_path, b"; filament used [g] = 0,0,0\n").estimates
    assert estimates["filament_used_grams"] == 0
    assert estimates["anycubic_tool_usage"] == [{"tool": 0, "grams": 0}]


def test_required_usage_validation_still_rejects_invalid_vectors(tmp_path):
    with pytest.raises(AnycubicError, match="usage vector"):
        inspect(tmp_path, base=GCODE.replace(b"3309.77,0,0", b"nan,0,0"))


def test_merging_fresh_unknown_estimates_removes_stale_amounts_and_error_markers():
    previous = {
        "print_time_seconds": 99,
        "filament_used_grams": 9,
        "filament_slots": [{"used_g": 9}],
        "anycubic_tool_usage": [{"tool": 0, "grams": 9}],
        "anycubic_estimates_error": True,
        "printer_type": "anycubic",
        "user_note": "preserved",
    }
    fresh = {"anycubic_estimates_version": ESTIMATES_VERSION, "anycubic_estimates_sha256": "a" * 64}
    assert merge_estimates(previous, fresh) == {"printer_type": "anycubic", "user_note": "preserved", **fresh}
    assert previous["anycubic_estimates_error"] is True
