GCODE = b"""; generated by AnycubicSlicerNext 2.0.0.3
; printer_model = Anycubic Kobra S1
; filament_type = PLA;PLA Matte;PETG
; filament_colour = #112233;#abcdef;#778899
; filament used [mm] = 1,0,2
T0
G1 X1 Y1
T2
M400
"""


def artifact(tmp_path, data=GCODE):
    path = tmp_path / "source.gcode"
    path.write_bytes(data)
    return inspect_print_file(path, "source.gcode", "Kobra S1")


def client():
    value = AnycubicMQTTClient("192.168.1.50", "fixture", tls_fingerprint="a" * 64)
    value._client = MagicMock()
    value._subscribed = True
    value.state.connected, value.state.state = True, "IDLE"
    value._last_message_monotonic = value._last_state_time = value._info_observed = time.monotonic()
    value._control_report(
        "info", {"data": {"features": {"auto_leveling_support": True, "camera_timelapse_support": 1}}}
    )
    return value


def single(tmp_path):
    return artifact(tmp_path, GCODE.replace(b"T2", b"T0").replace(b"1,0,2", b"1,0,0"))


def test_file_requirements_retain_original_sparse_tool_ids_and_md5(tmp_path):
    selected = artifact(tmp_path)
    assert selected.md5 == hashlib.md5(GCODE, usedforsecurity=False).hexdigest()
    assert selected.public() == {
        "model": "Kobra S1",
        "tools": [{"tool": 0, "type": "PLA", "color": "112233FF"}, {"tool": 2, "type": "PETG", "color": "778899FF"}],
    }
    assert inspect_print_file(selected.file.path, "source.gcode").file.model == "Kobra S1"


def test_zero_filled_unused_extruders_do_not_require_phantom_materials(tmp_path):
    data = GCODE.replace(b"T2", b"T0").replace(b"1,0,2", b"1,0,0").replace(b"PLA;PLA Matte;PETG", b"PLA")
    assert [item.tool for item in artifact(tmp_path, data).filaments] == [0]


