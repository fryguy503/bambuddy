@pytest.mark.parametrize("task", [123, "local-task-123"])
def test_start_requires_correlated_receipt_and_preserves_native_file_and_settings(tmp_path, task):
    value, selected = client(), single(tmp_path)
    context = value.file_session()

    def publish(kind, action, data, *, msgid):
        assert (kind, action) == ("print", "start")
        assert data["taskid"] == "-1" and data["filetype"] == data["project_type"] == 1
        assert data["filename"] == selected.file.filename and data["md5"] == selected.md5
        assert data["url"] is data["filepath"] is None
        assert data["task_settings"]["auto_leveling"] == 1
        assert data["task_settings"]["timelapse"] == {"status": 1, "count": 0, "type": 0, "mode": 0}
        value._print_report("print", {"action": "start", "msgid": "someone-else", "code": 200, "data": {"taskid": 99}})
        assert not value._print_pending["event"].is_set()
        value._print_report("print", {"action": "start", "msgid": msgid, "code": 200, "data": {"task_id": task}})
        return True

    value._publish = MagicMock(side_effect=publish)
    result = value.submit_print(context, selected, {"auto_leveling": True, "timelapse": True}, "queue-1", timeout=0.01)
    assert result["status"] == "accepted" and result["task_id"] == str(task)
    assert value.submit_print(context, selected, {"auto_leveling": True, "timelapse": True}, "queue-1") == result
    value._publish.assert_called_once()


