def test_ace_wire_index_uses_sorted_box_position_and_original_paint_index(tmp_path):
    value = client()
    value._telemetry.boxes = {
        1: {"id": 1, "tray": [{"id": 3, "tray_type": "PETG", "tray_color": "778899FF", "state": 3}]},
        0: {"id": 0, "tray": [{"id": 1, "tray_type": "PLA", "tray_color": "112233FF", "state": 3}]},
    }
    value._ace_seen = {0: time.monotonic(), 1: time.monotonic()}
    caps = value.print_capabilities()
    options = {
        "use_ace": True,
        "filament_mapping": [{"tool": 0, "box_id": 0, "slot_id": 1}, {"tool": 2, "box_id": 1, "slot_id": 3}],
    }
    data = print_data(artifact(tmp_path), options, caps["ace_slots"], caps["options"])
    assert [(row["paint_index"], row["ams_index"]) for row in data["ams_settings"]["ams_box_mapping"]] == [
        (0, 1),
        (2, 7),
    ]
    value._telemetry.boxes.pop(0)
    assert value.print_capabilities()["ace_slots"][0]["ams_index"] == 3


