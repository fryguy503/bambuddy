def test_a_correlated_rejection_or_disconnect_is_not_replayed(tmp_path):
    value, selected = client(), single(tmp_path)
    context = value.file_session()

    def reject(kind, action, data, *, msgid):
        value._print_report(kind, {"action": action, "msgid": msgid, "code": 403})
        return True

    value._publish = MagicMock(side_effect=reject)
    result = value.submit_print(context, selected, {}, "queue-rejected", timeout=0.01)
    assert result["status"] == "rejected"
    assert value.submit_print(context, selected, {}, "queue-rejected") == result
    value._publish.assert_called_once()
    value._publish = MagicMock(side_effect=lambda *args, **kwargs: value._reset_print_request() or True)
    assert value.submit_print(context, selected, {}, "queue-disconnected", timeout=0.01)["status"] == "unknown"
    assert value.submit_print(context, selected, {}, "queue-disconnected")["status"] == "unknown"
    value._publish.assert_called_once()


def test_a_late_receipt_cannot_accept_a_different_dispatch(tmp_path):
    value, selected = client(), single(tmp_path)
    context = value.file_session()
    value._publish = MagicMock(return_value=True)
    first = value.submit_print(context, selected, {}, "timed-out", timeout=0.01)
    assert first["status"] == "unknown"

    def publish(kind, action, data, *, msgid):
        value._print_report(kind, {"action": action, "msgid": first["msgid"], "code": 200, "data": {"taskid": 21}})
        assert not value._print_pending["event"].is_set()
        value._print_report(kind, {"action": action, "msgid": msgid, "code": 200, "data": {"taskid": 22}})
        return True

    value._publish = MagicMock(side_effect=publish)
    second = value.submit_print(context, selected, {}, "new-dispatch", timeout=0.01)
    assert second["status"] == "accepted" and second["task_id"] == "22"
    assert value.submit_print(context, selected, {}, "timed-out") == first
    value._publish.assert_called_once()


def test_session_replacement_wakes_submission_and_ignores_its_old_receipt(tmp_path):
    value, selected = client(), single(tmp_path)
    context, published, results = value.file_session(), threading.Event(), []
    value._device_id = "fixture"
    value._publish = MagicMock(side_effect=lambda *args, **kwargs: published.set() or True)
    worker = threading.Thread(
        target=lambda: results.append(value.submit_print(context, selected, {}, "replaced", timeout=1))
    )
    worker.start()
    assert published.wait(1)
    generation, connection = value._generation, value._client
    with value._lock:
        value._generation += 1
        value._reset_print_request()
    worker.join(1)
    assert not worker.is_alive() and results[0]["status"] == "unknown"
    message = MagicMock(
        topic="anycubic/anycubicCloud/v1/printer/public/20025/fixture/print/report",
        payload=json.dumps(
            {"type": "print", "action": "start", "msgid": results[0]["msgid"], "code": 200, "data": {"taskid": 23}}
        ).encode(),
        retain=False,
    )
    value._received(generation, connection, message)
    assert value.submit_print(context, selected, {}, "replaced") == results[0]
    value._publish.assert_called_once()


def test_cancellation_after_publish_does_not_claim_the_accepted_print_was_cancelled(tmp_path):
    value, selected, cancelled = client(), single(tmp_path), threading.Event()

    def publish(kind, action, data, *, msgid):
        cancelled.set()
        value._print_report(kind, {"action": action, "msgid": msgid, "code": 200, "data": {"taskid": 24}})
        return True

    value._publish = MagicMock(side_effect=publish)
    result = value.submit_print(value.file_session(), selected, {}, "cancel-race", timeout=0.01, cancelled=cancelled)
    assert result["status"] == "accepted"
    value._publish.assert_called_once()


@pytest.mark.parametrize("condition", ["stale", "session", "printing", "cancelled", "changed_file"])
def test_known_pre_submit_failures_send_nothing(tmp_path, condition):
    value, selected = client(), single(tmp_path)
    context = value.file_session()
    cancelled = threading.Event()
    value._publish = MagicMock()
    if condition == "stale":
        value._last_state_time -= 120
    elif condition == "session":
        value._generation += 1
    elif condition == "printing":
        value.state.state = "RUNNING"
    elif condition == "cancelled":
        cancelled.set()
    else:
        selected.file.path.write_bytes(GCODE)
    with pytest.raises(AnycubicError):
        value.submit_print(context, selected, {}, "queue-3", cancelled=cancelled)
    value._publish.assert_not_called()


