class Response:
    status = 200

    def __init__(self, payload, body):
        self.payload, self.body, self.wire = payload, body, b""
        self.content = self

    async def __aenter__(self):
        self.wire = b"".join([part async for part in self.body])
        return self

    async def __aexit__(self, *_):
        pass

    async def iter_chunked(self, _size):
        # Exercise a receipt split across transport chunks.
        yield self.payload[:5]
        yield self.payload[5:]


@pytest.mark.asyncio
async def test_multipart_preserves_native_fields_length_and_exact_file_bytes(tmp_path):
    export = artifact(tmp_path)
    client = connected()
    context = files.FileSession(HOST, "Kobra S1", client._generation, client._client, URL)
    response = None
    posted = {}

    def post(url, **kwargs):
        nonlocal response
        posted.update(url=url, **kwargs)
        response = Response(json.dumps({"code": 200, "data": {"gcode": export.filename}}).encode(), kwargs["data"])
        return response

    session = MagicMock(post=post)
    session.__aenter__.return_value = session
    progress = MagicMock()
    with patch.object(files.aiohttp, "ClientSession", return_value=session) as construct:
        assert await files.upload_gcode(client, context, export, progress=progress) == export.filename
    assert construct.call_args.kwargs["trust_env"] is False
    assert posted["allow_redirects"] is False
    assert posted["url"] == URL
    assert posted["headers"]["X-File-Length"] == str(len(GCODE))
    assert int(posted["headers"]["Content-Length"]) == len(response.wire)
    message = BytesParser(policy=policy.default).parsebytes(
        ("Content-Type: " + posted["headers"]["Content-Type"] + "\r\n\r\n").encode() + response.wire
    )
    parts = list(message.iter_parts())
    assert parts[0].get_param("name", header="content-disposition") == "filename"
    assert parts[0].get_payload(decode=True).decode() == export.filename
    assert parts[1].get_param("name", header="content-disposition") == "gcode"
    assert parts[1].get_payload(decode=True) == GCODE
    progress.assert_called_with(len(GCODE))


