@pytest.fixture
def native(monkeypatch):
    client = AnycubicMQTTClient("192.168.1.151", "CONNECTION-S1", model="Kobra S1", tls_fingerprint="a" * 64)
    client.state.connected = True
    client.state.state = "IDLE"
    client._last_message_monotonic = client._last_state_time = client._info_observed = time.monotonic()
    client._publish = MagicMock(side_effect=AssertionError("Connection checks must never publish printer commands"))
    monkeypatch.setattr(printer_manager, "_clients", {1: client})
    monkeypatch.setattr(printer_manager, "_awaiting_plate_clear", set())
    return client


def test_healthy_idle_native_client_is_connected_and_dispatch_eligible(native):
    assert native.state.connected is True
    assert printer_manager.is_connected(1) is True
    assert native.print_capabilities()["ready"] is True
    assert PrintScheduler()._is_printer_idle(1) is True
    native._publish.assert_not_called()


def test_stale_client_is_offline_and_loses_cached_inventory(native):
    native.state.raw_data["ams"] = [{"id": 0, "tray": []}]
    native._telemetry.boxes = {0: {"id": 0, "tray": []}}
    native._last_message_monotonic -= native.STALE_TIMEOUT + 1
    assert printer_manager.is_connected(1) is False
    assert native.state.connected is False
    assert native.state.state == "unknown"
    assert native.state.raw_data["ams"] == []
    assert native._telemetry.boxes == {}
    assert PrintScheduler()._is_printer_idle(1) is False
    native._publish.assert_not_called()


def test_disconnected_or_missing_client_remains_offline(native):
    native.state.connected = False
    assert printer_manager.is_connected(1) is False
    assert printer_manager.is_connected(99) is False
    assert PrintScheduler()._is_printer_idle(1) is False


def test_connected_idle_client_waits_for_native_readiness(native):
    native._info_observed = 0
    assert printer_manager.is_connected(1) is True
    assert native.print_capabilities()["ready"] is False
    assert PrintScheduler()._is_printer_idle(1) is False
    reason = PrintScheduler._pinned_hold_reason(1, "KS1", False)
    assert reason == "Waiting for Anycubic print readiness: KS1"
    assert PrintScheduler._is_busy_only(reason) is True


def test_running_native_client_is_connected_and_busy(native):
    native.state.state = "RUNNING"
    assert printer_manager.is_connected(1) is True
    assert PrintScheduler()._is_printer_idle(1) is False
    assert PrintScheduler._pinned_hold_reason(1, "KS1", False) == "Busy: KS1"


def test_native_plate_confirmation_is_required_with_global_toggle_off(native):
    printer_manager._awaiting_plate_clear.add(1)
    assert printer_manager.is_connected(1) is True
    assert PrintScheduler()._is_printer_idle(1, require_plate_clear=False) is False
    reason = PrintScheduler._pinned_hold_reason(1, "KS1", False)
    assert reason == "Waiting for plate confirmation: KS1"
    assert PrintScheduler._is_busy_only(reason) is False


