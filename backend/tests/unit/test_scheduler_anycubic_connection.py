@pytest.mark.asyncio
@pytest.mark.parametrize(
    "condition,reason",
    [
        ("healthy", None),
        ("readiness", "Waiting for Anycubic print readiness: KS1"),
        ("running", "Busy: KS1"),
        ("plate", "Waiting for plate confirmation: KS1"),
        ("stale", "Offline, no Auto On smart plug: KS1"),
        ("offline", "Offline, no Auto On smart plug: KS1"),
    ],
)
async def test_real_manager_connection_drives_native_queue_selection(queue_case, native, condition, reason):
    case = queue_case
    if condition == "readiness":
        native._info_observed = 0
    elif condition == "running":
        native.state.state = "RUNNING"
    elif condition == "plate":
        printer_manager._awaiting_plate_clear.add(1)
    elif condition == "stale":
        native._last_message_monotonic -= native.STALE_TIMEOUT + 1
    elif condition == "offline":
        native.state.connected = False
    await case.scheduler.check_queue()
    async with case.factory() as db:
        item = await db.get(PrintQueueItem, case.item_id)
        assert item.waiting_reason == reason
    if condition == "healthy":
        case.launched.assert_called_once()
        assert case.launched.call_args.args[0] == [case.item_id]
        case.plugs.assert_not_awaited()
    else:
        case.launched.assert_not_called()
        if condition not in {"stale", "offline"}:
            case.plugs.assert_not_awaited()
    if condition in {"readiness", "running"}:
        case.waiting.assert_not_awaited()
    case.power_on.assert_not_awaited()
    native._publish.assert_not_called()
