SOURCE = b"; generated by AnycubicSlicerNext 2.0.0.3\n; printer_model = Anycubic Kobra S1\n; filament_type = PLA\n; filament_colour = #112233\n; filament used [mm] = 100\nT0\nG1 X1 Y1\n"


@pytest.fixture
def prepare(monkeypatch, tmp_path):
    monkeypatch.setattr(registry_module, "entry_points", lambda **kwargs: [])
    registry = registry_module.PrinterPluginRegistry()
    monkeypatch.setattr(registry_module, "registry", registry)
    registry.load()
    plugin = AnycubicPrinterPlugin()
    registry.register(plugin)
    monkeypatch.setattr(api_module, "_bindings", {})
    monkeypatch.setattr(inventory, "capture", AsyncMock(return_value={"version": 1, "bindings": [], "skipped": []}))

    async def create(uri="archive:1", material="PLA", override=False, rejection_code=None):
        printer = SimpleNamespace(
            id=42,
            ip_address="192.168.50.50",
            serial_number="FULL-CORE-DISPATCH",
            access_code="",
            model="Kobra S1",
            plugin_id="anycubic",
            plugin_options={"tls_fingerprint": "a" * 64},
        )
        config = PrinterConfig.from_printer(printer)
        adapter = printer_api.create_connection(printer)
        connection, frames, catalog, captures = adapter._connection, [], [], []
        native = connection.native

        class Broker:
            def publish(self, _topic, payload, **_kwargs):
                packet = json.loads(payload)
                if (packet["type"], packet["action"]) == ("info", "query"):
                    native._file_report(
                        "info", {"data": {"urls": {"fileUploadurl": f"http://{config.ip_address}:18910/gcode_upload"}}}
                    )
                if (packet["type"], packet["action"]) == ("print", "start"):
                    frames.append(packet)
                    if rejection_code is not None:
                        native._print_report(
                            "print",
                            {
                                "action": "start",
                                "msgid": packet["msgid"],
                                "code": rejection_code,
                                "message": "PRIVATE-DEVICE-RESPONSE",
                            },
                        )
                        return SimpleNamespace(rc=0)
                    native._print_report(
                        "print",
                        {
                            "action": "start",
                            "msgid": packet["msgid"],
                            "code": 200,
                            "data": {"taskid": "full-core-native-ack"},
                        },
                    )
                return SimpleNamespace(rc=0)

        native._client, native._subscribed, native._device_id = Broker(), True, "fixture-device"
        report = {
            "action": "getInfo",
            "data": {
                "multi_color_box": [
                    {
                        "id": 0,
                        "slots": [
                            {"index": index, "status": 5, "edit_status": 1, "type": material, "color": [17, 34, 51]}
                            if index == 1
                            else {"index": index, "status": 4}
                            for index in range(4)
                        ],
                    }
                ]
            },
        }
        native._telemetry.apply("multiColorBox", report)
        native._observe_ace_drying(report)
        native.state.connected, native.state.state = True, "IDLE"
        native._last_state_time = native._last_message_monotonic = native._info_observed = time.monotonic()
        source = tmp_path / "source.gcode"
        source.write_bytes(SOURCE)
        alias = "uploaded-core-file.gcode"

        async def fake_upload(actual, _context, artifact, **_kwargs):
            assert actual is native and artifact.path.read_bytes() == SOURCE
            catalog[:] = [{"name": artifact.filename, "size": artifact.size, "is_dir": False}]

        monkeypatch.setattr(transport, "upload_gcode", fake_upload)
        monkeypatch.setattr(native, "list_files", lambda **_kwargs: {"files": catalog})
        description = plugin.describe_job(config, JobArtifact(uri=uri, filename=source.name, format="gcode"), source)
        job = JobRequest(
            job_id="frontend-opaque-id",
            artifact=description.artifact,
            selected_tool_ids=["tool:primary"],
            bindings=[MaterialBinding(input_id="T0", tool_id="tool:primary", source_id="material:ace:0:1")],
            options={"use_ace": True, "allow_material_type_mismatch": override},
        )
        original_invoke = plugin.invoke

        async def capture(*args):
            captures.append(args[-1])
            receipt = await original_invoke(*args)
            captures.append(receipt)
            return receipt

        monkeypatch.setattr(plugin, "invoke", capture)
        item = SimpleNamespace(
            id=22,
            sdk_job=job.model_dump(mode="json"),
            tool_ids=["tool:primary"],
            material_bindings={"T0": "material:ace:0:1"},
            job_options=job.options,
            plate_id=None,
        )
        with provider_context(config, plugin):
            assert await upload_file_async(config.ip_address, config.access_code, source, "/" + alias, printer_id=42)
        return SimpleNamespace(
            plugin=plugin,
            config=config,
            printer=printer,
            adapter=adapter,
            connection=connection,
            native=native,
            source=source,
            alias=alias,
            item=item,
            captures=captures,
            frames=frames,
            catalog=catalog,
        )

    return create


@pytest.mark.asyncio
@pytest.mark.parametrize("uri", ["archive:1", "library:2"])
async def test_real_upload_alias_survives_core_uri_rewrite_and_native_ack(prepare, uri):
    case = await prepare(uri)
    assert case.connection.journal.artifact(case.connection.printer_key, uri) is None
    uploaded = case.connection.journal.artifact(case.connection.printer_key, case.alias)
    assert uploaded is not None and uploaded["native_filename"] != case.alias
    with provider_context(case.config, case.plugin):
        assert await start_queue_job(case.item, case.printer, case.adapter, case.alias)
        assert await start_queue_job(case.item, case.printer, case.adapter, case.alias)
    assert case.item.sdk_job["artifact"]["uri"] == uri
    assert case.captures[0].parameters["artifact"]["uri"] == case.alias
    assert case.captures[0].parameters["artifact"]["sha256"] == uploaded["sha256"]
    assert case.captures[1].status == "accepted"
    assert len(case.frames) == 1
    assert case.frames[0]["data"]["filename"] == uploaded["native_filename"] == case.catalog[0]["name"]
    assert case.frames[0]["data"]["md5"] == uploaded["md5"]
    assert case.connection.journal.get("queue:22")["status"] == "accepted"
    assert case.source.read_bytes() == SOURCE


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "failure,reason",
    [
        ("type", "does not match the sliced"),
        ("stale", "unavailable or its material status is stale"),
        ("hold", "queue:prior-held"),
    ],
)
async def test_core_keeps_specific_rejection_without_publishing_or_replaying(prepare, failure, reason):
    case = await prepare(material="PETG" if failure == "type" else "PLA")
    if failure == "stale":
        case.native._ace_material_seen[0] -= case.native.STALE_TIMEOUT + 1
    if failure == "hold":
        case.connection.journal.begin(
            "queue:prior-held", {"status": "unknown", "native_filename": "prior-123456789abc.gcode"}
        )
    with provider_context(case.config, case.plugin), pytest.raises(PrinterPluginError, match=reason):
        await start_queue_job(case.item, case.printer, case.adapter, case.alias)
    assert case.captures[-1].status == "failed" and reason in case.captures[-1].error.message
    assert not case.frames and case.connection.journal.get("queue:22") is None


@pytest.mark.asyncio
async def test_explicit_type_override_survives_the_entire_core_pipeline(prepare):
    case = await prepare("library:2", material="PETG", override=True)
    with provider_context(case.config, case.plugin):
        assert await start_queue_job(case.item, case.printer, case.adapter, case.alias)
    assert len(case.frames) == 1
    assert case.frames[0]["data"]["ams_settings"]["ams_box_mapping"][0]["material_type"] == "PLA"
    assert case.connection.journal.get("queue:22")["options"]["allow_material_type_mismatch"] is True


@pytest.mark.asyncio
async def test_native_numeric_rejection_survives_core_and_journal_without_private_text_or_replay(prepare):
    case = await prepare(rejection_code=403)
    with provider_context(case.config, case.plugin), pytest.raises(PrinterPluginError, match="response code 403"):
        await start_queue_job(case.item, case.printer, case.adapter, case.alias)
    record = case.connection.journal.get("queue:22")
    assert record["status"] == "failed" and record["native_response_code"] == 403
    assert "PRIVATE" not in case.captures[-1].error.message
    with provider_context(case.config, case.plugin), pytest.raises(PrinterPluginError, match="already attempted"):
        await start_queue_job(case.item, case.printer, case.adapter, case.alias)
    assert len(case.frames) == 1
