@pytest.mark.asyncio
@pytest.mark.parametrize("change,recovery", [("empty", "material_selection"), ("stale", "refresh")])
async def test_preflight_rechecks_material_after_a_slow_source_inspection(
    queue_material, monkeypatch, change, recovery
):
    case = queue_material
    entered, release = threading.Event(), threading.Event()
    inspect = job_preflight.inspect_requirements

    def slow_inspection(*args, **kwargs):
        entered.set()
        assert release.wait(3), "Test must release the source inspection worker"
        return inspect(*args, **kwargs)

    monkeypatch.setattr(job_preflight, "inspect_requirements", slow_inspection)
    work = asyncio.create_task(preflight(case))
    try:
        assert await asyncio.to_thread(entered.wait, 2)
        if change == "empty":
            case.materials(empty_slot=1)
        else:
            case.native._ace_material_seen[0] -= case.native.STALE_TIMEOUT + 1
    finally:
        release.set()
    result = await asyncio.wait_for(work, 5)
    assert result["issues"][0]["recovery"] == recovery
    assert result["issues"][0]["resource_ids"] == ["material:ace:0:1"]
    assert case.connection.journal.get(case.job.job_id) is None
    case.native._client.publish.assert_not_called()


