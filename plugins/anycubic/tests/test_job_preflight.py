def test_requirement_cache_never_reuses_another_path_or_model_and_evicts_old_entries(queue_material, monkeypatch):
    case = queue_material
    monkeypatch.setattr(job_preflight, "_MAX_REQUIREMENTS", 2)
    inspect = MagicMock(wraps=job_preflight.inspect_print_file)
    monkeypatch.setattr(job_preflight, "inspect_print_file", inspect)
    first = job_preflight.inspect_requirements(case.path, case.path.name, case.config.model)
    assert job_preflight.inspect_requirements(case.path, case.path.name, case.config.model) is first
    assert inspect.call_count == 1
    for filename in ("second.gcode", "third.gcode"):
        path = case.path.with_name(filename)
        path.write_bytes(SOURCE)
        job_preflight.inspect_requirements(path, path.name, case.config.model)
    job_preflight.inspect_requirements(case.path, case.path.name, case.config.model)
    assert inspect.call_count == 4
    with pytest.raises(AnycubicError):
        job_preflight.inspect_requirements(case.path, case.path.name, "Kobra 3")
    with pytest.raises(AnycubicError, match="queued artifact changed"):
        job_preflight.inspect_requirements(case.path, case.path.name, case.config.model, expected_sha256="0" * 64)


@pytest.mark.asyncio
async def test_empty_slot_after_upload_returns_proof_only_before_dispatch_reservation(queue_material, monkeypatch):
    case = queue_material
    assert await preflight(case) == {"issues": []}
    case.materials(status=4)
    submit = MagicMock(side_effect=AssertionError("No print command is permitted"))
    monkeypatch.setattr(case.native, "submit_print", submit)
    result = await case.plugin.invoke(
        case.config,
        case.connection,
        OperationRequest(
            operation_id="job.start",
            parameters=case.job.model_dump(mode="json"),
        ),
    )
    assert result.status == "failed" and result.error.code == "job.material_selection_required"
    assert result.error.details["not_submitted"] is True
    assert result.error.details["issues"][0]["resource_ids"] == ["material:ace:0:1"]
    deferred = JobDispatchRejected(result).preflight
    assert deferred is not None
    assert (
        queue_hold(validate_job_preflight(case.plugin.describe_device(case.config), case.job, deferred))["kind"]
        == "material_selection"
    )
    assert case.connection.journal.get(case.job.job_id) is None
    case.usage.assert_not_awaited()
    submit.assert_not_called()
    case.native._client.publish.assert_not_called()


@pytest.mark.asyncio
async def test_material_failure_after_reservation_retains_unknown_hold_without_retry_proof(queue_material, monkeypatch):
    case = queue_material
    monkeypatch.setattr(case.native, "file_session", MagicMock(return_value=object()))
    monkeypatch.setattr(
        case.native,
        "submit_print",
        MagicMock(
            side_effect=MaterialMappingError(
                "A selected ACE slot became unavailable",
                code="anycubic.material_unavailable",
                tools=[0],
            )
        ),
    )
    result = await case.plugin.invoke(
        case.config,
        case.connection,
        OperationRequest(
            operation_id="job.start",
            parameters=case.job.model_dump(mode="json"),
        ),
    )
    assert result.status == "failed" and result.error.code == "anycubic.operation_rejected"
    assert JobDispatchRejected(result).preflight is None
    assert "not_submitted" not in result.error.details
    assert case.connection.journal.get(case.job.job_id)["status"] == "unknown"
    assert case.connection.journal.unresolved()[0]["job_id"] == case.job.job_id
    assert case.native.submit_print.call_count == 1
    case.native._client.publish.assert_not_called()
    again = await case.plugin.invoke(
        case.config,
        case.connection,
        OperationRequest(
            operation_id="job.start",
            parameters=case.job.model_dump(mode="json"),
        ),
    )
    assert again.status == "failed" and "not_submitted" not in again.error.details
    assert case.native.submit_print.call_count == 1
