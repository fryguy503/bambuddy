@pytest.mark.parametrize("bad_observation", ["predates_intent", "disconnected", "stale", "no_lifecycle"])
def test_cached_or_unfresh_lifecycle_cannot_establish_filename_ownership(tracked, bad_observation):
    before = tracked.seed()
    tracked.native._telemetry.apply(
        "info", {"data": {"state": "busy", "project": {"state": "printing", "filename": NATIVE_FILENAME, "taskid": -1}}}
    )
    tracked.native._last_message_time = time.time()
    if bad_observation == "predates_intent":
        tracked.native._last_message_time = datetime.fromisoformat(before["created_at"]).timestamp() - 1
    elif bad_observation == "disconnected":
        tracked.native.state.connected = False
    elif bad_observation == "stale":
        tracked.native._last_message_monotonic = time.monotonic() - tracked.native.STALE_TIMEOUT - 1
    else:
        tracked.native._telemetry.lifecycle_observed = False
    tracked.connection._observe_jobs()
    assert lifecycle(tracked) == []
    assert tracked.connection.journal.get(tracked.job.job_id) == before


def test_real_id_then_sentinel_and_restart_can_finish_verified_dispatch_without_replay(tracked):
    tracked.seed("accepted", native_job_id="assigned-native-task")
    tracked.observe(taskid="assigned-native-task")
    assert lifecycle(tracked) == ["job.started"]
    # A replacement observer has no in-memory lifecycle state. The durable
    # active observation authorizes terminal closeout, never print re-dispatch.
    restarted = tracked.plugin.create_connection(tracked.config, on_event=tracked.events.append)
    restarted.native.state.connected = True
    restarted.native._last_message_time = time.time()
    restarted.native._last_message_monotonic = restarted.native._last_state_time = time.monotonic()
    restarted.native._telemetry.apply(
        "info", {"data": {"state": "busy", "project": {"state": "finished", "filename": NATIVE_FILENAME, "taskid": -1}}}
    )
    restarted._observe_jobs()
    assert lifecycle(tracked) == ["job.started", "job.completed"]
    assert restarted.current_job.extensions["native_filename_verified"] is True
    assert restarted.native._print_attempts == {}
    assert tracked.frames == []


def test_concurrent_terminal_commit_cannot_resurrect_or_emit_owned_active_job(tracked, monkeypatch):
    tracked.seed("accepted")
    original_update = tracked.connection.journal.update

    def finalized_before_running(job_id, **fields):
        if fields.get("status") == "running":
            original_update(job_id, status="completed")
        return original_update(job_id, **fields)

    monkeypatch.setattr(tracked.connection.journal, "update", finalized_before_running)
    tracked.observe()
    assert lifecycle(tracked) == []
    assert tracked.connection.current_job is None
    assert tracked.connection.journal.get(tracked.job.job_id)["status"] == "completed"
    assert tracked.connection.dispatch_holds == []


@pytest.mark.parametrize(
    "expected,reported", [(None, -1), (None, "assigned-native-task"), ("assigned-native-task", -1)]
)
def test_legacy_same_filename_pending_intents_cannot_acquire_ambiguous_filename_ownership(tracked, expected, reported):
    first = tracked.seed("accepted", native_job_id=expected)
    second_job = tracked.job.model_copy(update={"job_id": "legacy-concurrent-job"})
    assert tracked.connection.journal.begin(
        second_job.job_id,
        {**first, "status": "unknown", "native_job_id": None, "bindings": second_job.model_dump(mode="json")},
    )
    tracked.observe(taskid=reported)
    assert lifecycle(tracked) == []
    tracked.callbacks["on_print_start"].assert_not_called()
    assert tracked.connection.journal.get(tracked.job.job_id)["status"] == "accepted"
    assert tracked.connection.journal.get(second_job.job_id)["status"] == "unknown"
    assert tracked.connection.current_job is None
    assert tracked.frames == []


def test_real_task_identity_can_disambiguate_legacy_same_filename_pending_intents(tracked):
    first = tracked.seed("accepted", native_job_id="assigned-native-task")
    second_job = tracked.job.model_copy(update={"job_id": "legacy-concurrent-job"})
    assert tracked.connection.journal.begin(
        second_job.job_id,
        {**first, "status": "unknown", "native_job_id": None, "bindings": second_job.model_dump(mode="json")},
    )
    tracked.observe(taskid="assigned-native-task")
    assert lifecycle(tracked) == ["job.started"]
    assert tracked.connection.current_job.job_id == tracked.job.job_id
    assert tracked.connection.journal.get(tracked.job.job_id)["status"] == "running"
    assert tracked.connection.journal.get(second_job.job_id)["status"] == "unknown"
    tracked.callbacks["on_print_start"].assert_called_once()
