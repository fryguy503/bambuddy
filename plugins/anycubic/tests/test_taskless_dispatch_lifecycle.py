def lifecycle(case):
    return [event.event for event in case.events if event.event.startswith("job.")]


def test_unchanged_running_reports_emit_progress_without_rewriting_the_dispatch(tracked, monkeypatch):
    from plugins.anycubic.payload import persistence

    tracked.seed()
    writes = []
    original_write = persistence.write_json

    def write(path, value):
        writes.append(path)
        original_write(path, value)

    monkeypatch.setattr(persistence, "write_json", write)
    tracked.observe()
    assert lifecycle(tracked) == ["job.started"] and len(writes) == 1
    first = tracked.connection.journal.get(tracked.job.job_id)
    for _ in range(6):
        tracked.observe()
    assert lifecycle(tracked) == ["job.started"] + ["job.progress"] * 6
    assert tracked.connection.journal.get(tracked.job.job_id) == first
    assert len(writes) == 1
    tracked.observe("finished")
    assert lifecycle(tracked)[-1] == "job.completed"
    assert tracked.connection.journal.get(tracked.job.job_id)["pending_outcome"] == "completed"
    assert len(writes) == 3  # The terminal observation and required plate hold remain durable.


@pytest.mark.asyncio
async def test_taskless_native_active_receipt_finish_cleanup_allows_next_job_without_replay(tracked):
    request = OperationRequest(
        operation_id="job.start", request_id="taskless-request", parameters=tracked.job.model_dump(mode="json")
    )
    accepted = await tracked.plugin.invoke(tracked.config, tracked.connection, request)
    assert accepted.status == "accepted" and len(tracked.frames) == 1
    assert tracked.connection.journal.get(tracked.job.job_id)["native_job_id"] is None
    assert lifecycle(tracked) == ["job.started"]
    assert tracked.connection.current_job.job_id == tracked.job.job_id
    assert tracked.connection.current_job.extensions["native_filename_verified"] is True
    assert tracked.connection.state.job.job_id == tracked.job.job_id
    assert tracked.connection.state.job.extensions["owned_by_bambuddy"] is True
    assert (await tracked.connection.operation_status(tracked.job.job_id)).status == "running"
    tracked.observe("paused")
    assert lifecycle(tracked) == ["job.started", "job.progress"]
    tracked.callbacks["on_print_start"].assert_called_once()

    tracked.observe("finished")
    tracked.observe("finished")
    assert lifecycle(tracked) == ["job.started", "job.progress", "job.completed"]
    tracked.callbacks["on_print_complete"].assert_called_once()
    assert tracked.connection.plate_clear_required is True
    assert tracked.connection.journal.get(tracked.job.job_id)["pending_outcome"] == "completed"
    await tracked.plugin.cleanup_after_print(42, {"job_id": tracked.job.job_id}, 123, logging.getLogger(__name__))
    tracked.complete.assert_awaited_once()
    assert tracked.connection.journal.unresolved() == []
    assert (await tracked.connection.operation_status(tracked.job.job_id)).status == "succeeded"

    tracked.receive("info", {"state": "free"})
    clear = await tracked.plugin.invoke(
        tracked.config, tracked.connection, OperationRequest(operation_id="job.clear_plate")
    )
    assert clear.status == "succeeded" and tracked.connection.plate_clear_required is False
    repeated = await tracked.plugin.invoke(tracked.config, tracked.connection, request)
    assert repeated.status == "failed" and len(tracked.frames) == 1
    next_job = tracked.job.model_copy(update={"job_id": "next-sdk-job"})
    accepted_next = await tracked.plugin.invoke(
        tracked.config,
        tracked.connection,
        OperationRequest(operation_id="job.start", parameters=next_job.model_dump(mode="json")),
    )
    assert accepted_next.status == "accepted" and len(tracked.frames) == 2


