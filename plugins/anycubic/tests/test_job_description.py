"""Real sliced-input routing and declarative controls, without printer/network I/O."""

import time

import pytest

from backend.app.printers.contracts import PrinterConfig, PrinterPluginError
from backend.app.printers.sdk import JobArtifact, validate_device, validate_job_description
from plugins.anycubic.payload.plugin import AnycubicPrinterPlugin

GCODE = b"""; generated by AnycubicSlicerNext 2.0.0.3
; printer_model = Anycubic Kobra S1
; filament_type = PLA;PLA Matte;PETG
; filament_colour = #112233;#abcdef;#778899
; filament used [mm] = 1,0,2
; filament used [g] = 4,0,8
T0
G1 X1 Y1
T2
M400
"""


def fixture(monkeypatch):
    plugin = AnycubicPrinterPlugin()
    config = PrinterConfig(
        "192.168.50.50",
        "JOB-DESCRIPTION-ONLY",
        "",
        model="Kobra S1",
        plugin_id=plugin.id,
        options={"tls_fingerprint": "a" * 64},
    )
    connection = plugin.create_connection(config)
    monkeypatch.setattr(
        connection.native,
        "control_capabilities",
        lambda: {
            "print_options": ["auto_leveling", "flow_calibration"],
            "ace_drying": [
                {
                    "id": 0,
                    "temp_min": 40,
                    "temp_max": 55,
                    "duration_min": 5,
                    "duration_max": 1440,
                    "duration_limits": [],
                }
            ],
        },
    )
    return plugin, config


def describe(plugin, config, tmp_path, data=GCODE, identity="library:1"):
    path = tmp_path / "sliced.gcode"
    path.write_bytes(data)
    artifact = JobArtifact(uri=identity, filename=path.name, format="gcode")
    return plugin.describe_job(config, artifact, path)


def test_sparse_inputs_keep_original_ids_mass_and_plugin_equivalence(monkeypatch, tmp_path):
    plugin, config = fixture(monkeypatch)
    first = describe(plugin, config, tmp_path)
    second = describe(plugin, config, tmp_path, identity="library:2")
    validate_job_description(plugin.describe_device(config), first)
    assert [item.id for item in first.inputs] == ["T0", "T2"]
    assert [item.required_mass_grams for item in first.inputs] == [4, 8]
    assert [item.routing_key for item in first.inputs] == [item.routing_key for item in second.inputs]
    assert first.inputs[0].routing_key != first.inputs[1].routing_key
    assert all(item.artifact_uri == "library:1" for item in first.inputs)
    assert all("material:external" not in item.compatible_source_ids for item in first.inputs)
    assert first.options_schema["properties"]["use_ace"]["const"] is True


def test_single_input_external_mode_and_original_option_defaults(monkeypatch, tmp_path):
    plugin, config = fixture(monkeypatch)
    value = describe(
        plugin, config, tmp_path, GCODE.replace(b"T2", b"T0").replace(b"1,0,2", b"1,0,0").replace(b"4,0,8", b"4,0,0")
    )
    assert len(value.inputs) == 1
    assert "material:external" in value.inputs[0].compatible_source_ids
    assert value.default_options == {
        "use_ace": True,
        "auto_leveling": False,
        "flow_calibration": False,
        "vibration_compensation": False,
        "timelapse": False,
        "allow_material_type_mismatch": False,
    }
    assert value.options_schema["properties"]["auto_leveling"]["title"] == "Bed leveling"
    assert value.options_schema["properties"]["timelapse"]["readOnly"] is True
    assert "const" not in value.options_schema["properties"]["use_ace"]
    assert value.extensions["bambuddy:ui"]["material_mode"]["external_source_id"] == "material:external"


def test_model_mismatch_is_rejected_before_options_are_advertised(monkeypatch, tmp_path):
    plugin, config = fixture(monkeypatch)
    with pytest.raises(PrinterPluginError, match="model"):
        describe(plugin, config, tmp_path, GCODE.replace(b"Kobra S1", b"Kobra 3"))


def test_presentation_is_explicit_and_opaque_resource_ids_do_not_change(monkeypatch):
    plugin, config = fixture(monkeypatch)
    device = validate_device(plugin.describe_device(config))
    resources = {item.id: item for item in device.resources}
    operations = {item.id: item for item in device.operations}
    assert resources["ace:0"].label == "ACE 1"
    assert resources["ace:1"].label == "ACE 2"
    assert resources["material:ace:0:0"].label == "ACE 1 slot 1"
    assert operations["anycubic.motion.home"].extensions["bambuddy:ui"]["icon"] == "home"
    assert operations["anycubic.material.feed"].parameters_schema["properties"]["action"]["x-enum-labels"] == [
        "Load",
        "Unload",
        "Stop",
    ]
    drying = operations["anycubic.drying.set"]
    assert drying.extensions["bambuddy:ui"]["state"]["temperature"] == "/drying/target_temp"
    assert drying.resource_parameters_schemas["ace:0"]["properties"]["temperature"]["maximum"] == 55
    assert drying.resource_parameters_schemas["ace:0"]["properties"]["duration_minutes"]["default"] == 240
    assert "material:external" not in operations["anycubic.material.feed"].resource_ids
    assert "file_upload" in device.capabilities
    assert device.extensions["bambuddy:file_upload"] == {"accept": [".gcode"], "max_bytes": 536870912}


def test_internal_feeder_is_not_an_ace_dryer():
    plugin = AnycubicPrinterPlugin()
    config = PrinterConfig(
        "192.168.50.50",
        "TEMPLATE-ONLY",
        "",
        model="Kobra X",
        plugin_id=plugin.id,
        options={"tls_fingerprint": "a" * 64},
    )
    device = plugin.describe_device(config)
    assert next(item for item in device.resources if item.id == "ace:-1").label == "Internal feeder"
    assert "ace:-1" not in next(item for item in device.operations if item.id == "anycubic.drying.set").resource_ids


def test_slot_presence_is_explicit_and_missing_or_stale_data_never_becomes_empty(monkeypatch):
    plugin, config = fixture(monkeypatch)
    connection = plugin.connections[config.serial_number]
    native = connection.native
    report = {
        "action": "getInfo",
        "data": {
            "multi_color_box": [
                {
                    "id": 0,
                    "slots": [
                        {"index": 0, "status": 4},
                        {"index": 1, "status": 5, "edit_status": 1, "type": "PLA", "color": [17, 34, 51]},
                        {"index": 2, "status": 5, "edit_status": 2, "type": "UNKNOWN", "color": [0, 0, 0]},
                        {"index": 3, "status": 0, "edit_status": 0, "type": "UNKNOWN", "color": [0, 0, 0]},
                    ],
                }
            ]
        },
    }
    native._telemetry.apply("multiColorBox", report)
    native._observe_ace_drying(report)
    native.state.connected = True
    native._last_message_monotonic = native._last_state_time = time.monotonic()
    snapshot = plugin.snapshot_device(config, connection)
    by_id = {item.resource_id: item for item in snapshot.resources}
    assert [by_id[f"material:ace:0:{slot}"].status for slot in range(4)] == [
        "empty",
        "loaded",
        "unconfigured",
        "unknown",
    ]
    assert by_id["material:ace:1:0"].status == "unknown"
    native._ace_material_seen[0] = time.monotonic() - native.STALE_TIMEOUT - 1
    stale = plugin.snapshot_device(config, connection)
    assert next(item for item in stale.resources if item.resource_id == "material:ace:0:0").status == "unknown"
