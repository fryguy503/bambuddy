def test_required_policy_covers_a_legacy_owner_hold_written_after_observer_cutover(tmp_path, monkeypatch):
    target = case(tmp_path, monkeypatch)
    observer = target.plugin.create_connection(target.config)
    assert observer.state.extensions["plate_clear_required"] is False
    archive = Path(__file__).resolve().parents[3] / "packages" / "anycubic" / "anycubic-0.1.4.bbp"
    with zipfile.ZipFile(archive) as legacy:
        tree = ast.parse(legacy.read("payload/connection.py"))
    connection = next(
        node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == "AnycubicConnection"
    )
    old_plate = next(node for node in connection.body if isinstance(node, ast.FunctionDef) and node.name == "_plate")
    namespace = {}
    exec(compile(ast.Module(body=[old_plate], type_ignores=[]), "published-0.1.4", "exec"), namespace)
    namespace["_plate"](target.connection, True)
    # An older retained workflow has no way to mutate the new observer's cache.
    # The host combines this declared policy with its old-owner awaiting flag.
    assert observer.journal.get("plate:" + observer.printer_key)["status"] == "plate_required"
    original_get = observer.journal.get
    monkeypatch.setattr(observer.journal, "get", MagicMock(side_effect=AssertionError("No snapshot journal I/O")))
    assert observer.state.extensions["plate_clear_required"] is False
    assert target.plugin.describe_device(target.config).extensions["plate_clear_policy"] == "required"
    monkeypatch.setattr(observer.journal, "get", original_get)
