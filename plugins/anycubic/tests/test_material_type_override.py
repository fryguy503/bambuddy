SOURCE = b"; generated by AnycubicSlicerNext 2.0.0.3\n; printer_model = Anycubic Kobra S1\n; filament_type = PLA\n; filament_colour = #112233\n; filament used [mm] = 100\n; filament used [g] = 3\nT0\nM104 S215\nG1 X1 Y1\n"


@pytest.fixture
def artifact(tmp_path):
    path = tmp_path / "source.gcode"
    path.write_bytes(SOURCE)
    return inspect_print_file(path, path.name, "Kobra S1")


def options(override=False):
    return {
        "use_ace": True,
        "filament_mapping": [{"tool": 0, "box_id": 0, "slot_id": 1}],
        "allow_material_type_mismatch": override,
    }


def slot(material="PETG", available=True):
    return {
        "box_id": 0,
        "slot_id": 1,
        "ams_index": 1,
        "material_type": material,
        "color": [100, 110, 120, 255],
        "available": available,
    }


def test_type_override_only_relaxes_type_equality_and_adds_no_wire_fields(artifact):
    with pytest.raises(AnycubicError, match="does not match"):
        print_data(artifact, options(False), [slot()], [])
    output = print_data(artifact, options(True), [slot()], [])
    mapping = output["ams_settings"]["ams_box_mapping"][0]
    assert mapping == {
        "paint_index": 0,
        "ams_index": 1,
        "paint_color": [17, 34, 51, 255],
        "ams_color": [100, 110, 120, 255],
        "material_type": "PLA",
    }
    assert "allow_material_type_mismatch" not in json.dumps(output)
    assert output["md5"] == artifact.md5 and output["filename"] == artifact.file.filename
    assert set(output["task_settings"]) == {
        "auto_leveling",
        "vibration_compensation",
        "flow_calibration",
        "dry_mode",
        "ai_settings",
        "timelapse",
        "drying_settings",
        "model_objects_skip_parts",
    }
    assert artifact.file.path.read_bytes() == SOURCE
    assert artifact.file.sha256 == hashlib.sha256(SOURCE).hexdigest()
    omitted = options(False)
    omitted.pop("allow_material_type_mismatch")
    assert print_data(artifact, omitted, [slot("PLA")], []) == print_data(artifact, options(False), [slot("PLA")], [])


@pytest.mark.parametrize("value", ["true", "false", 1, 0, None, [], {}])
def test_override_requires_an_explicit_boolean(value):
    with pytest.raises(AnycubicError, match="explicit boolean"):
        validate_options(options(value))
    assert validate_options({})["allow_material_type_mismatch"] is False


@pytest.mark.parametrize("material,available", [("", True), ("UNKNOWN", True), ("?", True), ("PETG", False)])
def test_override_does_not_authorize_empty_unknown_or_unavailable_material(artifact, material, available):
    with pytest.raises(AnycubicError):
        print_data(artifact, options(True), [slot(material, available)], [])


def case(tmp_path, monkeypatch):
    plugin = AnycubicPrinterPlugin()
    config = PrinterConfig(
        "192.168.50.50",
        "MATERIAL-OVERRIDE",
        "",
        model="Kobra S1",
        plugin_id=plugin.id,
        options={"tls_fingerprint": "a" * 64},
    )
    events, frames = [], []
    connection = plugin.create_connection(config, on_event=events.append)
    path = tmp_path / "source.gcode"
    path.write_bytes(SOURCE)
    artifact = inspect_print_file(path, path.name, config.model)
    uri = "library:override-fixture"
    connection.journal.save_artifact(
        connection.printer_key,
        uri,
        {
            "path": str(path),
            "source_filename": path.name,
            "native_filename": artifact.file.filename,
            "sha256": artifact.file.sha256,
            "estimates": artifact.estimates,
        },
    )
    usage = AsyncMock(return_value={"version": 1, "bindings": [], "skipped": []})
    monkeypatch.setattr(inventory, "capture", usage)

    def ready(target):
        native = target.native

        class Broker:
            def publish(self, topic, payload, *, qos, retain):
                packet = json.loads(payload)
                frames.append(packet)
                if packet["type"] == "print" and packet["action"] == "start":
                    native._print_report(
                        "print",
                        {
                            "action": "start",
                            "msgid": packet["msgid"],
                            "code": 200,
                            "data": {"taskid": "native-material-override"},
                        },
                    )
                return SimpleNamespace(rc=0)

        native._client, native._subscribed, native._device_id = Broker(), True, "fixture-device"
        report = {
            "action": "getInfo",
            "data": {
                "multi_color_box": [
                    {
                        "id": 0,
                        "slots": [
                            {"index": index, "status": 5, "edit_status": 1, "type": "PETG", "color": [100, 110, 120]}
                            if index == 1
                            else {"index": index, "status": 4}
                            for index in range(4)
                        ],
                    }
                ]
            },
        }
        native._telemetry.apply("multiColorBox", report)
        native._observe_ace_drying(report)
        native.state.connected, native.state.state = True, "IDLE"
        native._last_state_time = native._last_message_monotonic = native._info_observed = time.monotonic()
        return native

    native = ready(connection)
    job = JobRequest(
        job_id="job:material-override",
        artifact=JobArtifact(uri=uri, filename=path.name, format="gcode", sha256=artifact.file.sha256),
        selected_tool_ids=["tool:primary"],
        bindings=[MaterialBinding(input_id="T0", tool_id="tool:primary", source_id="material:ace:0:1")],
        options={"use_ace": True},
    )
    return SimpleNamespace(
        plugin=plugin,
        config=config,
        connection=connection,
        native=native,
        job=job,
        artifact=artifact,
        usage=usage,
        events=events,
        frames=frames,
        ready=ready,
    )


@pytest.mark.asyncio
async def test_sdk_plan_override_is_validated_persisted_and_sent_once(tmp_path, monkeypatch):
    target = case(tmp_path, monkeypatch)
    denied = await target.plugin.invoke(
        target.config,
        target.connection,
        OperationRequest(operation_id="job.start", parameters=target.job.model_dump(mode="json")),
    )
    assert denied.status == "failed" and not target.frames
    assert target.connection.journal.get(target.job.job_id) is None
    target.usage.assert_not_awaited()
    job = target.job.model_copy(update={"options": {"use_ace": True, "allow_material_type_mismatch": True}})
    assert (
        validate_job_request(target.plugin.describe_device(target.config), job).options["allow_material_type_mismatch"]
        is True
    )
    request = OperationRequest(
        operation_id="job.start", request_id="material-override-request", parameters=job.model_dump(mode="json")
    )
    accepted = await target.plugin.invoke(target.config, target.connection, request)
    assert accepted.status == "accepted" and len(target.frames) == 1
    record = target.connection.journal.get(job.job_id)
    assert record["options"]["allow_material_type_mismatch"] is True
    assert record["bindings"]["options"]["allow_material_type_mismatch"] is True
    assert target.frames[0]["data"]["ams_settings"]["ams_box_mapping"][0]["material_type"] == "PLA"
    assert (await target.plugin.invoke(target.config, target.connection, request)).status == "accepted"
    assert len(target.frames) == 1


@pytest.mark.asyncio
async def test_string_override_and_foreign_source_cannot_enter_a_sdk_plan(tmp_path, monkeypatch):
    target = case(tmp_path, monkeypatch)
    bad = target.job.model_copy(update={"options": {"use_ace": True, "allow_material_type_mismatch": "true"}})
    with pytest.raises(ValueError):
        validate_invocation(
            target.plugin.describe_device(target.config),
            OperationRequest(operation_id="job.start", parameters=bad.model_dump(mode="json")),
        )
    with pytest.raises(AnycubicError, match="explicit boolean"):
        await target.connection._start_job(
            OperationRequest(operation_id="job.start", parameters=bad.model_dump(mode="json"))
        )
    foreign = target.job.model_copy(
        update={
            "options": {"allow_material_type_mismatch": True},
            "bindings": [MaterialBinding(input_id="T0", tool_id="tool:primary", source_id="source:foreign")],
        }
    )
    result = await target.plugin.invoke(
        target.config,
        target.connection,
        OperationRequest(operation_id="job.start", parameters=foreign.model_dump(mode="json")),
    )
    assert result.status == "failed" and not target.frames
    assert target.connection.journal.get(target.job.job_id) is None


@pytest.mark.asyncio
async def test_post_preflight_freshness_is_rechecked_even_with_override(tmp_path, monkeypatch):
    target = case(tmp_path, monkeypatch)

    async def stale_after_policy_check(*_):
        target.native._ace_material_seen[0] = time.monotonic() - target.native.STALE_TIMEOUT - 1
        return {"version": 1, "bindings": [], "skipped": []}

    target.usage.side_effect = stale_after_policy_check
    job = target.job.model_copy(update={"options": {"use_ace": True, "allow_material_type_mismatch": True}})
    result = await target.plugin.invoke(
        target.config,
        target.connection,
        OperationRequest(operation_id="job.start", parameters=job.model_dump(mode="json")),
    )
    assert result.status == "failed" and not target.frames
    assert target.native._ace_seen[0] > target.native._ace_material_seen[0]


@pytest.mark.asyncio
async def test_plate_hold_survives_restart_and_ack_emits_clear_snapshot_before_dispatch(tmp_path, monkeypatch):
    target = case(tmp_path, monkeypatch)
    target.connection._plate(True)
    restarted = target.plugin.create_connection(target.config, on_event=target.events.append)
    assert restarted.plate_clear_required is True
    original_get = restarted.journal.get
    monkeypatch.setattr(
        restarted.journal, "get", MagicMock(side_effect=AssertionError("Snapshots must not read journal"))
    )
    assert restarted.state.extensions["plate_clear_required"] is True
    monkeypatch.setattr(restarted.journal, "get", original_get)
    target.ready(restarted)
    bridge = HostEventBridge(target.config, target.plugin, {})
    adapter = PrinterConnectionAdapter(target.config, restarted, provider=target.plugin)
    adapter._event_bridge = bridge

    def emit(event):
        target.events.append(event)
        assert bridge.emit(event)

    restarted.on_event = emit
    restarted._emit("device.snapshot", restarted.state.model_dump(mode="json"))
    assert adapter.state.device_snapshot.extensions["plate_clear_required"] is True
    assert adapter.state.plate_clear_required is True
    job = target.job.model_copy(update={"options": {"use_ace": True, "allow_material_type_mismatch": True}})
    start = OperationRequest(operation_id="job.start", parameters=job.model_dump(mode="json"))
    assert (await target.plugin.invoke(target.config, restarted, start)).status == "failed"
    assert not target.frames
    clear = await target.plugin.invoke(target.config, restarted, OperationRequest(operation_id="job.clear_plate"))
    assert clear.status == "succeeded"
    assert restarted.journal.get("plate:" + restarted.printer_key)["status"] == "resolved"
    assert target.events[-1].event == "device.snapshot"
    assert target.events[-1].data["extensions"]["plate_clear_required"] is False
    assert bridge.latest_snapshot.extensions["plate_clear_required"] is False
    assert adapter.state.device_snapshot.extensions["plate_clear_required"] is False
    assert adapter.state.plate_clear_required is False
    assert (await target.plugin.invoke(target.config, restarted, start)).status == "accepted"
    assert len(target.frames) == 1


