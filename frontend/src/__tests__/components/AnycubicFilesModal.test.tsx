import { beforeEach, describe, expect, it, vi } from 'vitest';
import { screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { render } from '../utils';
import { api } from '../../api/client';
import { AnycubicFilesModal } from '../../components/AnycubicFilesModal';

describe('Native Anycubic files', () => {
  beforeEach(() => {
    sessionStorage.clear();
    vi.spyOn(api, 'listAnycubicFiles').mockResolvedValue({ path: '/', page: 1, pages: 1, total: 1, pagination: 'local', files: [{ name: 'stored.gcode', size: 123, is_dir: false, path: '/stored.gcode' }] });
  });
  it('lists stored files and displays upload confirmation without a print action', async () => {
    const user = userEvent.setup();
    const job = { id: 'job1', printer_id: 7, filename: 'new-unique.gcode', size: 123, sent: 123, phase: 'completed' as const, message: null };
    const upload = vi.spyOn(api, 'uploadAnycubicFile').mockResolvedValue(job);
    vi.spyOn(api, 'getAnycubicTransfer').mockResolvedValue(job);
    render(<AnycubicFilesModal printerId={7} printerName="S1" onClose={() => {}} />);
    await screen.findByText('stored.gcode');
    expect(screen.queryByRole('button', { name: 'Print' })).not.toBeInTheDocument();
    const file = new File(['; generated by AnycubicSlicerNext'], 'export.gcode', { type: 'text/plain' });
    await user.upload(screen.getByLabelText('Upload'), file);
    await user.click(screen.getByRole('button', { name: 'Upload' }));
    await waitFor(() => expect(upload).toHaveBeenCalledWith(7, file, expect.any(Function)));
    expect(await screen.findByText('Success')).toBeInTheDocument();
  });
  it('shows a transfer error and leaves the catalog available for inspection', async () => {
    const user = userEvent.setup();
    vi.spyOn(api, 'uploadAnycubicFile').mockRejectedValue(new Error('Wrong Anycubic model'));
    render(<AnycubicFilesModal printerId={7} printerName="S1" onClose={() => {}} />);
    await screen.findByText('stored.gcode');
    await user.upload(screen.getByLabelText('Upload'), new File(['wrong'], 'wrong.gcode'));
    await user.click(screen.getByRole('button', { name: 'Upload' }));
    expect(await screen.findByRole('alert')).toHaveTextContent('Wrong Anycubic model');
    expect(screen.getByText('stored.gcode')).toBeInTheDocument();
  });
});
